-- QueueLess database schema. Run in Supabase SQL Editor.
create extension if not exists pgcrypto;
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null, category text not null,
  price numeric(10,2) not null check (price >= 0),
  description text default '', emoji text default '🍽️',
  popular boolean default false, available boolean default true, prep integer default 5
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  token text unique not null, customer text not null, items jsonb not null,
  total numeric(10,2) not null check (total >= 0),
  status text not null default 'Order placed' check (status in ('Order placed','Preparing','Ready for pickup','Collected')),
  created_at timestamptz not null default now(), eta integer default 10
);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
-- Permissive demo policies only. Replace with authenticated role-based policies before production.
create policy "demo read menu" on public.menu_items for select using (true);
create policy "demo manage menu" on public.menu_items for all using (true) with check (true);
create policy "demo read orders" on public.orders for select using (true);
create policy "demo create orders" on public.orders for insert with check (true);
create policy "demo update orders" on public.orders for update using (true) with check (true);
